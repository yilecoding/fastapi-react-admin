/**
 * 列表页的默认每页条数。
 *
 * 收成一个常量而不是各页写 `search.size ?? 20`：原来 `?? 10` 散在 8 个页面里
 * （用户/公告/字典/在线用户/登录日志/操作日志 各一处，日志页的 queryKey 拼装还各多一处），
 * 改默认值就是「改 8 个地方、漏一个不报错、只表现为某一页跟别人不一样」。
 *
 * ⚠️ 这个值必须落在 `DataTablePagination` 的 `pageSizeOptions`（默认 `[10, 20, 30, 50]`）里。
 * 不在选项里的话，关闭态的 Select 会显示一个下拉里根本选不到的数字，
 * 用户改完就回不去了。
 *
 * **不进 URL**：默认值不写进 search params 是刻意的 —— 写进去之后
 * 「用户显式选了 20」和「用户没选、恰好是默认」就分不出来了，
 * 将来改默认值也没法让老链接跟着走。只有用户动过分页条才会出现 `size=`。
 */
export const DEFAULT_PAGE_SIZE = 20

/**
 * 🔴 **「回到第一页」要写成 `page: undefined`，不是 `page: 1`。**
 *
 * 和 `size` 同一条道理（见上），但漏得更彻底：改筛选条件时必须跳回第一页
 * （否则在第 5 页改条件、结果只有 3 条 → 空页，看起来像「什么都没查到」），
 * 而各页一律写的是 `patch({ …, page: 1 })` —— 于是 `?page=1` 出现在**每一个**
 * 列表页的地址栏里，全仓 59 处。
 *
 * ```
 * /log/login?start_time=2026-08-16+00%3A00%3A00&end_time=…&page=1
 *                                                          ~~~~~~ 永远是它
 * ```
 *
 * `undefined` 在 TanStack 的 `encode()` 里会被跳过，所以「不写」就是「第一页」。
 * 不为此导一个 `FIRST_PAGE` 常量：`page: undefined` 在调用处已经够清楚，
 * 而多一个 import 会摊到 11 个页面上。
 */

/**
 * 宫格视图的默认每页条数（文件管理）。
 *
 * 和列表页不同是刻意的：宫格一行放 4~6 张卡，24 正好铺满整屏且不留半行。
 * 它配的是自己的 `pageSizeOptions={[24, 48, 96]}` —— 都是 12 的倍数，
 * 换列数（4/6 列）都不会在最后一行留下孤零零的一两张卡。
 */
export const DEFAULT_GRID_PAGE_SIZE = 24
